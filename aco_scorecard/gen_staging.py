"""Generate the dbt staging models and source definitions from config/schema_mapping.yml.

One staging model per published file keeps every year's SQL explicit and reviewable, while the
YAML stays the single place where a column mapping is decided. Generated files carry a header
saying so; `python -m aco_scorecard.gen_staging --check` fails if they drift from the YAML
(the pytest suite runs it).
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path

import yaml

from .mapping import PLACEHOLDER, Field, Mapping, Source, load_mapping
from .paths import DBT_DIR, RAW_DIR

STAGING = DBT_DIR / "models" / "staging"
SQL_TYPES = {"varchar": "varchar", "number": "double", "flag": "boolean", "date": "date", "county_count": "double"}
HEADER = "-- Generated by aco_scorecard/gen_staging.py from config/schema_mapping.yml (version {version}).\n-- Do not edit by hand: change the YAML and regenerate.\n"


def q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def render_value(f: Field, src: Source | None) -> str:
    if src is None:
        return f"cast(null as {SQL_TYPES[f.type]})"
    if src.expr:
        return PLACEHOLDER.sub(lambda m: "{{ parse_number('" + q(m.group(1)) + "') }}", src.expr)
    col = q(src.column)
    if f.type == "varchar":
        expr = "{{ clean_text('" + col + "') }}"
    elif f.type == "number":
        expr = "{{ parse_number('" + col + "') }}"
    elif f.type == "flag":
        expr = "{{ parse_flag('" + col + "') }}"
    elif f.type == "date":
        expr = "{{ parse_date('" + col + "') }}"
    elif f.type == "county_count":
        expr = "{{ parse_county_count('" + col + "') }}"
    else:
        raise ValueError(f"unknown type {f.type}")
    if src.scale is not None:
        expr = f"{expr} * {src.scale}"
    return expr


def render_track(spec: dict) -> tuple[str, str]:
    if "flags" in spec:
        whens = "\n".join(f"        when trim({q(col)}) = '1' then '{code}'" for col, code in spec["flags"].items())
        default = f"'{spec['default']}'" if spec.get("default") else "null"
        case = f"case\n{whens}\n        else {default}\n    end"
        count = " + ".join(f"(case when trim({q(col)}) = '1' then 1 else 0 end)" for col in spec["flags"])
        if spec.get("default"):
            count = f"greatest({count}, 1)"
        return case, count
    col = q(spec["code"]["column"])
    whens = "\n".join(f"        when '{raw}' then '{code}'" for raw, code in spec["code"]["values"].items())
    case = f"case trim({col})\n{whens}\n    end"
    codes = ", ".join(f"'{raw}'" for raw in spec["code"]["values"])
    count = f"(case when trim({col}) in ({codes}) then 1 else 0 end)"
    return case, count


def render_financial(m: Mapping, period: dict) -> str:
    pid = period["id"]
    lines = [
        f"    '{pid}' as performance_period_id",
        f"    {period['performance_year']} as performance_year",
        f"    '{period['id_system']}' as aco_id_system",
        f"    '{period['period_rule']}' as period_rule",
    ]
    for f in m.fields:
        lines.append(f"    {render_value(f, f.sources.get(pid))} as {f.name}")
    track_case, track_count = render_track(m.tracks[pid])
    lines.append(f"    {track_case} as track_code")
    lines.append(f"    {track_count} as track_flag_count")
    lines += ["    _source_file_key", "    _source_sha256", "    _source_row_number", "    _loaded_at"]
    body = ",\n".join(lines)
    return (
        HEADER.format(version=m.version)
        + f"-- Source: raw.{period['file_key']} (Performance Year Financial and Quality Results, period {pid}).\n\n"
        + f"with source as (\n    select * from {{{{ source('cms_raw', '{period['file_key']}') }}}}\n)\n\n"
        + f"select\n{body}\nfrom source\n"
    )


def render_quality(m: Mapping, period: dict) -> str | None:
    pid = period["id"]
    rows = m.quality.get(pid) or []
    if not rows:
        return None
    id_col = q(m.fields[0].sources[pid].column)  # aco_source_id
    cols = ", ".join(q(r["column"]) for r in rows)
    values = ",\n        ".join(
        f"('{r['column']}', '{r['measure_key']}', '{r['collection']}', {float(r['scale']) if r['scale'] else 1.0})" for r in rows
    )
    return (
        HEADER.format(version=m.version)
        + f"-- Source: raw.{period['file_key']}; one row per ACO, measure and collection type for period {pid}.\n\n"
        + f"with source as (\n    select {{{{ clean_text('{id_col}') }}}} as aco_source_id, {cols}\n    from {{{{ source('cms_raw', '{period['file_key']}') }}}}\n),\n\n"
        + f"long_format as (\n    select aco_source_id, source_column, raw_value\n    from source\n    unpivot include nulls (raw_value for source_column in ({cols}))\n),\n\n"
        + f"column_map (source_column, measure_key, collection_type, scale) as (\n    values\n        {values}\n)\n\n"
        + "select\n"
        + f"    '{pid}' as performance_period_id,\n"
        + f"    {period['performance_year']} as performance_year,\n"
        + "    l.aco_source_id,\n"
        + "    c.measure_key,\n"
        + "    c.collection_type,\n"
        + "    l.source_column,\n"
        + "    l.raw_value,\n"
        + "    {{ parse_number('l.raw_value') }} * c.scale as measure_value,\n"
        + "    {{ measure_status('l.raw_value') }} as value_status\n"
        + "from long_format as l\n"
        + "inner join column_map as c on l.source_column = c.source_column\n"
    )


def render_county(m: Mapping, period: dict) -> str:
    pid = period["id"]
    lines = [f"    '{pid}' as performance_period_id", f"    {period['performance_year']} as performance_year"]
    for f in m.county_fields:
        src = f.sources.get(pid)
        lines.append(f"    {render_value(f, src)} as {f.name}")
        if f.type == "county_count":
            lines.append("    {{ county_status('" + q(src.column) + "') }} as " + f"{f.name}_status")
    lines += ["    _source_file_key", "    _source_sha256", "    _source_row_number", "    _loaded_at"]
    return (
        HEADER.format(version=m.version)
        + f"-- Source: raw.{period['county_file_key']} (Number of ACO Assigned Beneficiaries by County, period {pid}).\n\n"
        + f"with source as (\n    select * from {{{{ source('cms_raw', '{period['county_file_key']}') }}}}\n)\n\n"
        + "select\n" + ",\n".join(lines) + "\nfrom source\n"
    )


def model_name(kind: str, pid: str) -> str:
    return f"stg_{kind}__py{pid.lower()}"


def render_sources(m: Mapping) -> str:
    manifest = {}
    mpath = RAW_DIR / "manifest.json"
    if mpath.exists():
        manifest = {r["key"]: r for r in json.loads(mpath.read_text())["files"]}
    tables = []
    for p in m.periods:
        for key, series in ((p["file_key"], "Performance Year Financial and Quality Results"), (p.get("county_file_key"), "Number of ACO Assigned Beneficiaries by County")):
            if not key:
                continue
            desc = f"{series}, period {p['id']}, loaded as text exactly as published."
            tables.append({"name": key, "description": desc, "meta": {"period_id": p["id"], "source_url": manifest.get(key, {}).get("url")}})
    doc = {
        "version": 2,
        "sources": [
            {
                "name": "cms_raw",
                "description": "CMS Medicare Shared Savings Program public use files from data.cms.gov, loaded by aco_scorecard/ingest.py.",
                "schema": "raw",
                "loaded_at_field": "_loaded_at",
                "freshness": {"warn_after": {"count": 45, "period": "day"}},
                "tables": tables,
            }
        ],
    }
    return "# Generated by aco_scorecard/gen_staging.py. Do not edit by hand.\n" + yaml.safe_dump(doc, sort_keys=False, width=120)


def render_staging_docs(m: Mapping) -> str:
    models = []
    fin_cols = [{"name": "performance_period_id", "description": "CMS performance period id (2019 and 2019A are separate files)."}]
    fin_cols += [{"name": f.name, "description": f.description + (f" Unit: {f.unit}." if f.unit else "")} for f in m.fields]
    fin_cols += [
        {"name": "track_code", "description": "Track decoded from the period's flag or code columns (see the tracks section of the mapping)."},
        {"name": "track_flag_count", "description": "Number of track flags set; must be exactly 1."},
    ]
    column_tests = {
        "aco_source_id": ["not_null", "unique"],
        "performance_period_id": ["not_null"],
        "track_code": ["not_null"],
        "track_flag_count": [{"accepted_values": {"arguments": {"values": [1], "quote": False}}}],
    }
    for p in m.periods:
        cols = []
        for c in fin_cols:
            c = dict(c)
            if c["name"] in column_tests:
                c["data_tests"] = column_tests[c["name"]]
            cols.append(c)
        models.append(
            {
                "name": model_name("puf", p["id"]),
                "description": f"Typed, renamed PUF columns for period {p['id']} (one row per ACO).",
                "columns": cols,
            }
        )
        if m.quality.get(p["id"]):
            models.append(
                {
                    "name": model_name("puf_quality", p["id"]),
                    "description": f"Quality measure results for period {p['id']} in long format (one row per ACO, measure and collection type).",
                    "columns": [
                        {"name": "value_status", "data_tests": [{"accepted_values": {"arguments": {"values": ["reported", "not_reported", "suppressed_small_cell", "not_applicable", "reporting_error", "cahps_waived_auto_credit", "pay_for_reporting_suppressed"]}}}]},
                    ],
                }
            )
        if p.get("county_file_key"):
            models.append(
                {
                    "name": model_name("county", p["id"]),
                    "description": f"Assigned beneficiaries by county of residence for period {p['id']}.",
                    "columns": [
                        {"name": "aco_source_id", "data_tests": ["not_null"]},
                        {"name": "total_assigned_beneficiaries_status", "data_tests": [{"accepted_values": {"arguments": {"values": ["reported", "suppressed", "blank_suppressed_or_missing"]}}}]},
                    ],
                }
            )
    return "# Generated by aco_scorecard/gen_staging.py. Do not edit by hand.\n" + yaml.safe_dump({"version": 2, "models": models}, sort_keys=False, width=120)


def planned_files(m: Mapping) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for p in m.periods:
        files[STAGING / "puf" / f"{model_name('puf', p['id'])}.sql"] = render_financial(m, p)
        qsql = render_quality(m, p)
        if qsql:
            files[STAGING / "puf_quality" / f"{model_name('puf_quality', p['id'])}.sql"] = qsql
        if p.get("county_file_key"):
            files[STAGING / "county" / f"{model_name('county', p['id'])}.sql"] = render_county(m, p)
    files[STAGING / "_sources.yml"] = render_sources(m)
    files[STAGING / "_staging_models.yml"] = render_staging_docs(m)
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if generated files differ from what is on disk")
    args = ap.parse_args(argv)
    m = load_mapping()
    files = planned_files(m)
    drift = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            # the sources file embeds URLs from the local manifest; ignore it when no manifest exists
            drift.append(str(path.relative_to(DBT_DIR)))
            if current:
                sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True), str(path), "expected", n=1))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    # remove stale generated models
    stale = []
    for sub in ("puf", "puf_quality", "county"):
        for p in (STAGING / sub).glob("*.sql"):
            if p not in files:
                stale.append(p)
                if not args.check:
                    p.unlink()
    if args.check:
        if drift or stale:
            print(f"generated staging files are out of date: {drift + [str(s) for s in stale]}")
            return 1
        print(f"staging models match the mapping ({len(files)} files)")
        return 0
    print(f"wrote {len(files)} staging files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
